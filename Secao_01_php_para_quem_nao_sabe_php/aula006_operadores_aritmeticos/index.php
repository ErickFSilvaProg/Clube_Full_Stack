<?php

/*

https://www.php.net/manual/pt_BR/language.operators.php

    Operadores Aritméticos:

        () → Parênteses
        ** → Exponenciação
        *  → Multiplicação
        /  → Divisão
        %  → Módulo
        +  → Adição
        -  → Subtração

*/


// Variáveis:
$number1 = 10;
$number2 = 20;
$number3 = 5.5;

// Exponenciação:
echo $number1 ** 2;
echo "\n";

// Multiplicação:
echo $number1 * $number2;
echo "\n";

// Divisão:
echo $number2 / $number3;
echo "\n";

// Módulo:
echo $number1 % $number3;
echo "\n";

// Adição:
echo $number2 + $number1;
echo "\n";

// Subtração:
echo $number3 - $number1;
echo "\n";
