<?php

/* 
    — Operadores de Incremento e Decremento:

        ++$x (Pré-incremento): Soma 1 ao valor de $x primeiro e depois retorna o novo valor.
        $x++ (Pós-incremento): Retorna o valor atual de $x primeiro e depois soma 1 à variável.

        --$x (Pré-decremento): Subtrai 1 do valor de $x primeiro e depois retorna o novo valor.
        $x-- (Pós-decremento): Retorna o valor atual de $x primeiro e depois subtrai 1 da variável.

*/


// Variáveis:
$x = 10;


// 
echo $x;
echo "\n";
echo "\n";

echo ++$x;
echo "\n";

echo $x++;
echo "\n";

echo --$x;
echo "\n";

echo $x--;
echo "\n";
echo "\n";

echo $x;
echo "\n";